export const ATLAS: Record<Lang, typeof en> = {en, mn};
export type AtlasCopy = typeof en;

const RUNTIME: Record<string, string> = {
  'The anatomy catalogue could not be loaded.': 'Анатомийн каталогийг ачаалж чадсангүй.',
  'Could not load the anatomy.': 'Анатомийг ачаалж чадсангүй.',
  'Could not assemble anatomy geometry.': 'Анатомийн геометрийг угсарч чадсангүй.',
};

export function runtimeError(message: string, lang: Lang) {
  if (lang !== 'mn') return message;
  return RUNTIME[message] ?? message;
}

export function cameraError(message: string, lang: Lang) {
  if (lang !== 'mn') return message;
  if (/NotAllowed|Permission|denied/i.test(message)) return mn.romLab.cameraDenied;
  if (message === 'Could not start the camera / pose model.') return mn.romLab.cameraFailed;
  return message;
}

/** System overview in the active language. Named structure notes stay in their source language. */
export function systemDescription(id: SystemId, lang: Lang) {
  return ATLAS[lang].systems[id].description;
}
