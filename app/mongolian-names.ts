const ROMAN = /^(.*) \((i{1,3}|iv|v|vi{1,3}|ix|x|xi{1,2})\)$/;

function genitive(phrase: string) {
  const cut = phrase.lastIndexOf(' ') + 1, word = phrase.slice(cut);
  return phrase.slice(0, cut) + (GENITIVE[word] ?? guessGenitive(word));
}

/** Regular genitive endings by final letter and vowel harmony; irregular words are listed above. */
function guessGenitive(word: string) {
  const back = /[аоуыя]/.test(word) && !/[эөүе]/.test(word);
  if (/(аа|ээ|оо|өө|уу|үү)$/.test(word)) return word + (back ? 'ны' : 'ний');
  if (word.endsWith('и')) return word + (back ? 'ны' : 'йн');
  if (word.endsWith('й')) return word + 'н';
  if (/[бвгджзклмнпрстфхцчшщ]$/.test(word)) return word + (back ? 'ын' : 'ийн');
  return word + 'ийн';
}

function muscle(name: string): string | null {
  const words = name.split(' ');
  const action = MUSCLE_ACTIONS[words[0]];
  if (!action) return null;
  const objects: string[] = [], qualifiers: string[] = [];
  for (let i = 1; i < words.length; i++) {
    const pair = `${words[i]} ${words[i + 1] ?? ''}`;
    if (MUSCLE_OBJECTS[pair]) { objects.push(MUSCLE_OBJECTS[pair]); i++; continue; }
    if (MUSCLE_OBJECTS[words[i]]) { objects.push(MUSCLE_OBJECTS[words[i]]); continue; }
    if (MUSCLE_QUALIFIERS[words[i]]) { qualifiers.push(MUSCLE_QUALIFIERS[words[i]]); continue; }
    return null;
  }
  return [...objects, ...qualifiers, action, 'булчин'].join(' ');
}

function translate(name: string): string | null {
  if (TERMS[name]) return TERMS[name];
  const roman = ROMAN.exec(name);
  if (roman) {
    const base = translate(roman[1]);
    return base && `${base} (${roman[2].toUpperCase()})`;
  }
  if (name.startsWith('set of ')) return translate(name.slice(7));
  // "X of Y" → "Y-ийн X"; the first "of" splits, so chains nest from the right.
  const of = name.indexOf(' of ');
  if (of > 0) {
    const headName = name.slice(0, of), head = OWNED[headName] ?? translate(headName), owner = translate(name.slice(of + 4));
    if (!head || !owner) return null;
    // Drop a word the owner already says ("зовхины" in the eyelid's own tarsal plate).
    const ownerGenitive = genitive(owner), repeat = ownerGenitive.slice(ownerGenitive.lastIndexOf(' ') + 1);
    return `${ownerGenitive} ${head.split(' ').filter(word => word !== repeat).join(' ') || head}`;
  }
  const side = /^(left|right) (.+)$/.exec(name);
  if (side) {
    const rest = translate(side[2]);
    return rest && `${side[1] === 'left' ? 'зүүн' : 'баруун'} ${rest}`;
  }
  // Modifiers + the longest known head phrase.
  const words = name.split(' ');
  for (let i = 1; i < words.length; i++) {
    const head = TERMS[words.slice(i).join(' ')];
    if (!head) continue;
    const mods = words.slice(0, i).map(word => MODIFIERS[word]);
    if (mods.some(mod => !mod)) return muscle(name);
    const pick = (kind: Kind) => mods.filter(mod => mod![1] === kind).map(mod => mod![0]);
    return [...pick('ord'), ...pick('rel'), ...pick('pos'), head].join(' ');
  }
  return muscle(name);
}

const cache = new Map<string, string | null>();

/** The Mongolian name for an atlas structure, or null when part of it is not in the term list. */
export function mongolianName(name: string): string | null {
  const key = name.toLowerCase().trim();
  if (!cache.has(key)) cache.set(key, translate(key));
  return cache.get(key)!;
}

/** The name to show in the chosen language: Mongolian when it can be built, otherwise the atlas name. */
export function localName(name: string, lang: string) {
  if (lang !== 'mn') return name;
  const mn = mongolianName(name);
  return mn ? mn.charAt(0).toUpperCase() + mn.slice(1) : name;
}
