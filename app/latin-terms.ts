const VESSEL_OR_NERVE = /\b(arter(y|ies)|veins?|nerves?|branch(es)?|plexus|nodes?|lymphatic|ganglion|ramus|vessels?)\b/;

function plain(name: string) {
  return name
    .toLowerCase()
    .replace(/\s*\((i{1,3}|iv|v|vi{1,3}|ix|x|xi{1,2})\)$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

const cache = new Map<string, string | null>();

function lookup(name: string): string | null {
  const full = plain(name), bare = full.replace(/^(left|right) /, '');
  const listed = LATIN[full] ?? LATIN[bare];
  if (listed) return listed;
  const of = bare.indexOf(' of ');
  if (of > 0 && PART_LATIN[bare.slice(0, of)]) {
    const whole = latinName(bare.slice(of + 4));
    if (whole) return `${whole}, ${PART_LATIN[bare.slice(0, of)]}`;
  }
  if (!VESSEL_OR_NERVE.test(bare)) {
    // The reference entries name the card's Latin, so they win over the shorter fact notes.
    const curated = resolveBoneAtlas(bare)?.latin ?? resolveStructureAtlas(bare)?.latin ?? resolveStructureFact(bare)?.latin;
    if (curated) return curated;
  }
  return null;
}

/** The Latin name of an atlas structure, or null when no curated term covers it. */
export function latinName(name: string): string | null {
  const key = name.toLowerCase();
  if (!cache.has(key)) cache.set(key, lookup(name));
  return cache.get(key)!;
}

/** Lower-cased Latin with the usual abbreviations and their full words removed, so "n. medianus", "nervus
 *  medianus" and "medianus" all meet "N. medianus". Used for both the query and the indexed names. */
export function latinKey(text: string): string {
  return text
    .toLowerCase()
    .replace(/[.,;:()]/g, ' ')
    .replace(/\b(mm?|aa?|vv?|nn?|rr?|lig|ligg|art|artt|musculus|musculi|arteria|arteriae|vena|venae|nervus|nervi)\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Every Latin key a structure answers to: its own Latin name plus the landmark terms of its reference entry
 *  ("caput femoris" finds the femur). */
export function latinSearchKeys(name: string): string[] {
  const own = latinName(name);
  const bare = plain(name).replace(/^(left|right) /, '');
  const entry = VESSEL_OR_NERVE.test(bare) ? null : (resolveBoneAtlas(bare) ?? resolveStructureAtlas(bare));
  const keys = [own, ...(entry?.terms.map(term => term.latin) ?? [])].filter((x): x is string => !!x);
  // The written form keeps its abbreviation, so "a. femoralis" ranks the artery above the vein.
  return [...new Set([...keys.map(key => key.toLowerCase().replace(/\s+/g, ' ')), ...keys.map(latinKey)])];
}

/** How well `text` answers `term`: 0 exact, 1 prefix, 2 word start, 3 anywhere, Infinity not at all. */
export function matchRank(text: string, term: string): number {
  if (!term || !text) return Infinity;
  if (text === term) return 0;
  if (text.startsWith(term)) return 1;
  if (text.includes(` ${term}`) || text.includes(`-${term}`)) return 2;
  return text.includes(term) ? 3 : Infinity;
}
