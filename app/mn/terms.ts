/** Латин нэр томьёог хэлбэрээр нь олох туслах функц. */
export function latinTermMn(latin: string): string | undefined {
  const key = latin.toLowerCase().replace(/\s+/g, ' ').trim().replace(/\.+$/, '');
  const direct = LATIN_TERM_MN[key];
  if (direct !== undefined) return direct;

  // Тэмдэглэгээний үгээр (жишээ: "processus articularis (zygapophysis) superior") дахин хайна.
  const marked = key.match(/\(([^)]+)\)/);
  if (marked) {
    const words = marked[1].split(/\s+/).filter(Boolean);
    for (const word of words) {
      const markedValue = LATIN_TERM_MN[word];
      if (markedValue !== undefined) return markedValue;
    }
  }
  return undefined;
}
